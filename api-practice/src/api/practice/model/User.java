package api.practice.model;

/**
 * Modelo de dominio para representar un usuario de DummyJSON.
 * Esta clase permite mapear los campos importantes del JSON a un objeto Java.
 */
public class User {

    private int id;
    private String firstName;
    private String lastName;
    private int age;
    private String email;
    private String phone;
    private String city;

    public User() {
    }

    public User(int id, String firstName, String lastName, int age, String email, String phone, String city) {
        this.id = id;
        this.firstName = firstName;
        this.lastName = lastName;
        this.age = age;
        this.email = email;
        this.phone = phone;
        this.city = city;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getFirstName() {
        return firstName;
    }

    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getCity() {
        return city;
    }

    public void setCity(String city) {
        this.city = city;
    }

    public String getFullName() {
        return firstName + " " + lastName;
    }
}
